export const dictionaries = { uz, ru } satisfies Record<Locale, Record<DictKey, string>>

/** Replaces every `{var}` placeholder. Usable outside React. */
export function translate(locale: Locale, key: DictKey, vars?: Record<string, string | number>): string {
  let str: string = dictionaries[locale][key] ?? dictionaries.uz[key] ?? key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) str = str.split(`{${k}}`).join(String(v))
  }
  return str
}
